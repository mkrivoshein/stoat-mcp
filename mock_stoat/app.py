_ulid_lock = threading.Lock()
_ulid_last = [0, 0]  # last millisecond used, counter within it


def new_ulid(at_ms: int | None = None) -> str:
    """Return a ULID; IDs generated by this process sort in creation order."""
    with _ulid_lock:
        millis = at_ms if at_ms is not None else int(time.time() * 1000)
        millis = max(millis, _ulid_last[0])
        _ulid_last[1] = _ulid_last[1] + 1 if millis == _ulid_last[0] else 0
        _ulid_last[0] = millis
        counter = _ulid_last[1]
    head = ""
    for _ in range(10):
        head = ALPHABET[millis % 32] + head
        millis //= 32
    tail = ""
    for _ in range(6):
        tail = ALPHABET[counter % 32] + tail
        counter //= 32
    return head + tail + "".join(random.choice(ALPHABET) for _ in range(10))


def error(status: int, kind: str, **extra: Any) -> JSONResponse:
    return JSONResponse({"type": kind, **extra}, status_code=status)


class MockStoat:
    """In-memory state for the mock. Tests inspect it directly."""

    def __init__(self, seed: dict[str, Any] | None = None) -> None:
        seed = copy.deepcopy(seed or DEFAULT_SEED)
        self.lock = threading.Lock()
        self.tokens: dict[str, str] = {}
        self.users: dict[str, dict[str, Any]] = {}
        for bot in seed.get("bots", []):
            token = bot.pop("token")
            bot["bot"] = {"owner": "01HOWNER000000000000000000"}
            self.tokens[token] = bot["_id"]
            self.users[bot["_id"]] = bot
        for user in seed.get("users", []):
            self.users[user["_id"]] = user

        self.servers: dict[str, dict[str, Any]] = {}
        self.channels: dict[str, dict[str, Any]] = {}
        for server in seed.get("servers", []):
            channels = server.pop("channels", [])
            server["channel_ids"] = [c["_id"] for c in channels]
            server.setdefault("members", [])
            server.setdefault("nicknames", {})
            self.servers[server["_id"]] = server
            for channel in channels:
                channel["server"] = server["_id"]
                self.channels[channel["_id"]] = channel

        self.messages: dict[str, list[dict[str, Any]]] = {cid: [] for cid in self.channels}
        start = int(time.time() * 1000) - 60_000
        for offset, msg in enumerate(seed.get("messages", [])):
            msg = {"_id": new_ulid(start + offset), "content": "", **msg}
            self.messages[msg["channel"]].append(msg)

        self.attachments: dict[str, dict[str, Any]] = {}
        self.requests: list[dict[str, Any]] = []
        self.pending_rate_limits = 0

    # Helpers for tests ----------------------------------------------------

    def bot_id(self, token: str) -> str:
        return self.tokens[token]

    def all_messages(self) -> list[dict[str, Any]]:
        return [m for msgs in self.messages.values() for m in msgs]

    def inject_rate_limit(self, count: int = 1) -> None:
        self.pending_rate_limits += count

    # Request plumbing ----------------------------------------------------

    def authenticate(self, request: Request) -> str | JSONResponse:
        self.requests.append({
            "method": request.method,
            "path": request.url.path,
            "token": request.headers.get("x-bot-token"),
            "query": dict(request.query_params),
        })
        if self.pending_rate_limits > 0:
            self.pending_rate_limits -= 1
            return error(429, "RateLimited", retry_after=20)
        user_id = self.tokens.get(request.headers.get("x-bot-token", ""))
        if user_id is None:
            return error(401, "InvalidSession")
        return user_id

    def is_member(self, user_id: str, server_id: str) -> bool:
        return user_id in self.servers[server_id]["members"]

    def visible_channel(self, user_id: str, channel_id: str) -> dict[str, Any] | JSONResponse:
        channel = self.channels.get(channel_id)
        if channel is None or not self.is_member(user_id, channel["server"]):
            return error(404, "NotFound")
        return channel

    def public_channel(self, channel: dict[str, Any]) -> dict[str, Any]:
        return dict(channel)

    def users_for(self, messages: list[dict[str, Any]], server_id: str) -> tuple[list, list]:
        ids = {m["author"] for m in messages}
        users = [self.users[i] for i in ids if i in self.users]
        nicknames = self.servers[server_id]["nicknames"]
        members = [
            {"_id": {"server": server_id, "user": uid}, "nickname": nicknames[uid]}
            for uid in ids if uid in nicknames
        ]
        return users, members


def create_app(state: MockStoat | None = None) -> Starlette:
    state = state or MockStoat()

    async def root(request: Request) -> JSONResponse:
        base = str(request.base_url).rstrip("/")
        return JSONResponse({
            "revolt": "mock",
            "features": {"autumn": {"enabled": True, "url": f"{base}/autumn"}},
        })

    async def users_me(request: Request) -> JSONResponse:
        user_id = state.authenticate(request)
        if isinstance(user_id, JSONResponse):
            return user_id
        return JSONResponse(state.users[user_id])

    async def get_user(request: Request) -> JSONResponse:
        user_id = state.authenticate(request)
        if isinstance(user_id, JSONResponse):
            return user_id
        user = state.users.get(request.path_params["user_id"])
        return JSONResponse(user) if user else error(404, "NotFound")

    async def get_server(request: Request) -> JSONResponse:
        user_id = state.authenticate(request)
        if isinstance(user_id, JSONResponse):
            return user_id
        server = state.servers.get(request.path_params["server_id"])
        if server is None or not state.is_member(user_id, server["_id"]):
            return error(404, "NotFound")
        include = request.query_params.get("include_channels") == "true"
        channels = (
            [state.public_channel(state.channels[c]) for c in server["channel_ids"]]
            if include else list(server["channel_ids"])
        )
        return JSONResponse({"_id": server["_id"], "name": server["name"], "channels": channels})

    async def get_channel(request: Request) -> JSONResponse:
        user_id = state.authenticate(request)
        if isinstance(user_id, JSONResponse):
            return user_id
        channel = state.visible_channel(user_id, request.path_params["channel_id"])
        if isinstance(channel, JSONResponse):
            return channel
        return JSONResponse(state.public_channel(channel))

    async def messages(request: Request) -> JSONResponse:
        user_id = state.authenticate(request)
        if isinstance(user_id, JSONResponse):
            return user_id
        channel = state.visible_channel(user_id, request.path_params["channel_id"])
        if isinstance(channel, JSONResponse):
            return channel
        if channel["channel_type"] != "TextChannel":
            return error(400, "InvalidOperation")
        if request.method == "POST":
            return await post_message(request, user_id, channel)

        params = request.query_params
        limit = min(max(int(params.get("limit", 50)), 1), 100)
        history = sorted(state.messages[channel["_id"]], key=lambda m: m["_id"], reverse=True)
        if params.get("before"):
            history = [m for m in history if m["_id"] < params["before"]]
        history = history[:limit]
        if params.get("include_users") == "true":
            users, members = state.users_for(history, channel["server"])
            return JSONResponse({"messages": history, "users": users, "members": members})
        return JSONResponse(history)

    async def post_message(request: Request, user_id: str, channel: dict[str, Any]) -> JSONResponse:
        body = await request.json()
        content = body.get("content") or ""
        attachment_ids = body.get("attachments") or []
        if not content and not attachment_ids:
            return error(400, "EmptyMessage")
        if len(content) > MESSAGE_LIMIT:
            return error(400, "FailedValidation", error=f"content exceeds {MESSAGE_LIMIT} chars")

        attachments = []
        with state.lock:
            for aid in attachment_ids:
                attachment = state.attachments.get(aid)
                if attachment is None or attachment["uploader"] != user_id or attachment["used"]:
                    return error(400, "InvalidAttachment", id=aid)
            for aid in attachment_ids:
                state.attachments[aid]["used"] = True
                attachments.append({k: v for k, v in state.attachments[aid].items() if k not in {"data", "used"}})

            for reply in body.get("replies") or []:
                if not any(m["_id"] == reply["id"] for m in state.messages[channel["_id"]]):
                    return error(400, "InvalidReply", id=reply["id"])

            message: dict[str, Any] = {
                "_id": new_ulid(),
                "channel": channel["_id"],
                "author": user_id,
                "content": content,
            }
            if attachments:
                message["attachments"] = attachments
            if body.get("replies"):
                message["replies"] = [r["id"] for r in body["replies"]]
            state.messages[channel["_id"]].append(message)
        return JSONResponse(message)

    async def search(request: Request) -> JSONResponse:
        user_id = state.authenticate(request)
        if isinstance(user_id, JSONResponse):
            return user_id
        if "bot" in state.users[user_id]:
            # Upstream rejects bot accounts before running the search.
            return error(400, "IsBot")
        channel = state.visible_channel(user_id, request.path_params["channel_id"])
        if isinstance(channel, JSONResponse):
            return channel
        body = await request.json()
        query = (body.get("query") or "").lower()
        limit = min(max(int(body.get("limit", 50)), 1), 100)
        hits = [m for m in state.messages[channel["_id"]] if query in m["content"].lower()]
        hits.sort(key=lambda m: m["_id"], reverse=True)
        hits = hits[:limit]
        if body.get("include_users"):
            users, members = state.users_for(hits, channel["server"])
            return JSONResponse({"messages": hits, "users": users, "members": members})
        return JSONResponse(hits)

    async def upload(request: Request) -> JSONResponse:
        user_id = state.authenticate(request)
        if isinstance(user_id, JSONResponse):
            return user_id
        form = await request.form()
        upload = form.get("file")
        if upload is None or isinstance(upload, str):
            return error(400, "MissingFile")
        data = await upload.read()
        file_id = new_ulid()
        with state.lock:
            state.attachments[file_id] = {
                "_id": file_id,
                "tag": "attachments",
                "filename": upload.filename,
                "size": len(data),
                "uploader": user_id,
                "data": data,
                "used": False,
            }
        return JSONResponse({"id": file_id})

    app = Starlette(routes=[
        Route("/", root),
        Route("/users/@me", users_me),
        Route("/users/{user_id}", get_user),
        Route("/servers/{server_id}", get_server),
        Route("/channels/{channel_id}", get_channel),
        Route("/channels/{channel_id}/messages", messages, methods=["GET", "POST"]),
        Route("/channels/{channel_id}/search", search, methods=["POST"]),
        Route("/autumn/attachments", upload, methods=["POST"]),
    ])
    app.state.mock = state
    return app


def load_seed() -> dict[str, Any] | None:
    path = os.environ.get("MOCK_STOAT_SEED")
    if not path:
        return None
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)
